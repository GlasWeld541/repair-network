-- GlasWeld's own revenue reporting (Derek, 2026-09-15 call).
--
-- The jobs ledger shows what each SHOP invoiced its customer. Nothing showed what GLASWELD earned
-- from the referral fee. Derek: "otherwise we're just going to have money showing up and no way to
-- reconcile it." He asked for income month by month, amounts owed to us, and 30/60/90 aging,
-- because the big replacement partners are invoiced to an AP contact and will age.
--
-- Aggregation lives in the database rather than the browser on purpose. One fee event is written
-- per completed job, so this table grows 1:1 with claim volume (see ops/backlog.md REX-19); a page
-- that fetched every event and summed it in JS would work today at 6 rows and fall over later.
--
-- Fee lifecycle these read:
--   pending   -> written when a job is marked Completed
--   invoiced  -> the 1st-of-month cron stamps invoiced_at
--   paid      -> stamped paid_at (auto-charge, once a processor exists)
--   waived / void -> deliberately excluded from revenue
--
-- Pure additions: four read-only functions, no table or data changes.

-- Totals for a period. `earned` counts fees generated by jobs completed in the window; `collected`
-- counts money actually received in the window (paid_at), which is a different period for the same
-- fee — that is the point, and why they are separate columns rather than one number.
create or replace function network.revenue_summary(p_from timestamptz, p_to timestamptz)
returns table (
  earned_cents      bigint,
  collected_cents   bigint,
  waived_cents      bigint,
  outstanding_cents bigint,   -- as of now, not the window: what is still owed to us
  earned_events     bigint,
  outstanding_events bigint
)
language sql
stable
as $$
  select
    coalesce(sum(amount_cents) filter (
      where status not in ('void','waived') and occurred_at >= p_from and occurred_at < p_to), 0),
    coalesce(sum(amount_cents) filter (
      where status = 'paid' and paid_at >= p_from and paid_at < p_to), 0),
    coalesce(sum(amount_cents) filter (
      where status = 'waived' and coalesce(waived_at, occurred_at) >= p_from
        and coalesce(waived_at, occurred_at) < p_to), 0),
    coalesce(sum(amount_cents) filter (where status in ('pending','invoiced')), 0),
    coalesce(count(*) filter (
      where status not in ('void','waived') and occurred_at >= p_from and occurred_at < p_to), 0),
    coalesce(count(*) filter (where status in ('pending','invoiced')), 0)
  from network.billing_events;
$$;

-- Month-by-month, oldest first. generate_series so a month with no jobs shows as a zero row rather
-- than vanishing from the chart.
create or replace function network.revenue_by_month(p_months int default 12)
returns table (
  month           date,
  earned_cents    bigint,
  collected_cents bigint
)
language sql
stable
as $$
  with months as (
    select generate_series(
      date_trunc('month', now()) - make_interval(months => greatest(p_months, 1) - 1),
      date_trunc('month', now()),
      interval '1 month'
    ) as m
  )
  select
    months.m::date,
    coalesce((
      select sum(b.amount_cents) from network.billing_events b
      where b.status not in ('void','waived')
        and date_trunc('month', b.occurred_at) = months.m
    ), 0),
    coalesce((
      select sum(b.amount_cents) from network.billing_events b
      where b.status = 'paid' and date_trunc('month', b.paid_at) = months.m
    ), 0)
  from months
  order by months.m;
$$;

-- Aging of everything still owed to us. Age runs from the invoice date where one exists, else from
-- when the fee was earned — so an unpaid invoice from the 1st lands in 30+ once the next 1st passes,
-- which is how Derek described it.
create or replace function network.revenue_aging()
returns table (
  bucket      text,
  amount_cents bigint,
  events      bigint
)
language sql
stable
as $$
  with owed as (
    select amount_cents,
           (extract(epoch from (now() - coalesce(invoiced_at, occurred_at))) / 86400)::int as age_days
    from network.billing_events
    where status in ('pending','invoiced')
  ), bucketed as (
    select case
             when age_days <= 30 then '0-30'
             when age_days <= 60 then '31-60'
             when age_days <= 90 then '61-90'
             else '90+'
           end as bucket,
           amount_cents
    from owed
  ), labels as (
    select unnest(array['0-30','31-60','61-90','90+']) as bucket
  )
  select labels.bucket,
         coalesce(sum(bucketed.amount_cents), 0),
         coalesce(count(bucketed.*), 0)
  from labels left join bucketed on bucketed.bucket = labels.bucket
  group by labels.bucket
  order by case labels.bucket
             when '0-30' then 1 when '31-60' then 2 when '61-90' then 3 else 4 end;
$$;

-- Per provider for the window, so "who owes us" is answerable without opening each account.
create or replace function network.revenue_by_provider(
  p_from timestamptz, p_to timestamptz, p_limit int default 50
)
returns table (
  account_id        uuid,
  account_name      text,
  billing_profile   text,
  jobs              bigint,
  earned_cents      bigint,
  collected_cents   bigint,
  outstanding_cents bigint
)
language sql
stable
as $$
  select
    b.account_id,
    coalesce(a.account_name, '(unknown account)'),
    a.billing_profile_type,
    count(distinct b.job_id) filter (
      where b.status not in ('void','waived') and b.occurred_at >= p_from and b.occurred_at < p_to),
    coalesce(sum(b.amount_cents) filter (
      where b.status not in ('void','waived') and b.occurred_at >= p_from and b.occurred_at < p_to), 0),
    coalesce(sum(b.amount_cents) filter (
      where b.status = 'paid' and b.paid_at >= p_from and b.paid_at < p_to), 0),
    coalesce(sum(b.amount_cents) filter (where b.status in ('pending','invoiced')), 0)
  from network.billing_events b
  left join network.accounts a on a.id = b.account_id
  group by b.account_id, a.account_name, a.billing_profile_type
  -- An account with nothing in the window but an old unpaid balance still matters.
  having coalesce(sum(b.amount_cents) filter (
           where b.status not in ('void','waived')
             and b.occurred_at >= p_from and b.occurred_at < p_to), 0) > 0
      or coalesce(sum(b.amount_cents) filter (where b.status in ('pending','invoiced')), 0) > 0
  order by 7 desc, 5 desc
  limit greatest(p_limit, 1);
$$;

-- Called only from the admin-gated API route, which uses the service-role key.
grant execute on function network.revenue_summary(timestamptz, timestamptz) to service_role;
grant execute on function network.revenue_by_month(int) to service_role;
grant execute on function network.revenue_aging() to service_role;
grant execute on function network.revenue_by_provider(timestamptz, timestamptz, int) to service_role;

-- The aging and outstanding reads scan by status; the monthly reads scan by date. One partial index
-- covers what is owed (a small slice), one covers the time series.
create index if not exists billing_events_outstanding_idx
  on network.billing_events (coalesce(invoiced_at, occurred_at))
  where status in ('pending','invoiced');

create index if not exists billing_events_occurred_idx
  on network.billing_events (occurred_at);
